"""Proxy authentication for the MITM listener.

Every client must send `Proxy-Authorization: Basic base64("aster:<token>")` on CONNECT and on plain
HTTP requests. The token is a shared 64-hex-character secret generated by bootstrap.sh; it is not a
substitute for the source-address allowlist, it closes the remaining gap: any process that can reach
port 14322 still cannot use the proxy as an open relay.

Fail closed: a missing or unreadable token file stops mitmdump at startup, and any request without a
valid header gets 407. The header is never logged and, for plain HTTP, is removed before the request
is forwarded so the token is not handed to the destination server.
"""

import base64
import hmac
import re

USERNAME = "aster"
TOKEN_SHAPE = re.compile(r"[A-Za-z0-9._~-]{16,256}")


class ProxyTokenError(ValueError):
    """The configured proxy token is missing, unreadable, or malformed."""


def load_token(path: str) -> str:
    try:
        with open(path, encoding="utf-8") as handle:
            token = handle.read().strip()
    except OSError as error:
        raise ProxyTokenError("proxy token file could not be read") from error
    if not TOKEN_SHAPE.fullmatch(token):
        raise ProxyTokenError("proxy token file must contain 16-256 characters of [A-Za-z0-9._~-]")
    return token


class ProxyTokenGate:
    """Constant-time check of the Basic credentials on a proxy request."""

    def __init__(self, token: str, username: str = USERNAME) -> None:
        if not TOKEN_SHAPE.fullmatch(token):
            raise ProxyTokenError("proxy token must contain 16-256 characters of [A-Za-z0-9._~-]")
        self.username = username.encode("utf-8")
        self.token = token.encode("utf-8")

    @classmethod
    def from_file(cls, path: str) -> "ProxyTokenGate":
        return cls(load_token(path))

    def allows(self, header: str | None) -> bool:
        if not header:
            return False
        scheme, _, value = header.partition(" ")
        if scheme.lower() != "basic" or not value.strip():
            return False
        try:
            decoded = base64.b64decode(value.strip(), validate=True)
        except ValueError:
            return False
        username, separator, password = decoded.partition(b":")
        if not separator:
            return False
        # Compare bytes: compare_digest(str, str) raises on non-ASCII input.
        return hmac.compare_digest(username, self.username) and hmac.compare_digest(password, self.token)
